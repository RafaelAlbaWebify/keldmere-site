import { readFileSync } from "node:fs";
const read = (path) => readFileSync(path,"utf8");
const homepage=read("src/app/page.tsx");
const privacy=read("src/app/privacy/page.tsx");
const brand=read("BRAND.md");
const readme=read("README.md");
const docs=read("commercial/SALES-OPERATIONS-CHECKLIST.md");
const images=JSON.parse(read("commercial/IMAGE-ASSET-REGISTER.json")).assets;
const issues=[];
const check=(name,ok)=>{if(!ok)issues.push(name)};
check("Web-first offer missing on homepage",homepage.includes("Website Project")===false ? homepage.includes("Buy a website") : true);
check("Web-first offer missing in README",readme.includes("website design/development"));
check("Sales workflow missing website qualification",docs.includes("Website design/redesign:"));
check("Brand guidelines still focused on M365",brand.includes("Website Project") && brand.includes("Microsoft 365"));
check("Privacy inaccurately says fonts are requested",!privacy.includes("site loads fonts from Google Fonts"));
check("Homepage still directs premium Atrium gallery to legacy trades demo",!homepage.includes('href="/demos/trades/"'));
check("Homepage missing premium imagery",["hartwell-premium.webp","brightsmile-premium.webp","atrium-premium.webp"].every(f=>homepage.includes(f)&&images.some(a=>a.path==="public/images/"+f)));
check("Homepage missing contact or price paths",homepage.includes('id="contact"')&&homepage.includes('id="website-plans"'));
check("Static hosting disabled",read("next.config.ts").includes('output: "export"'));
console.log(JSON.stringify({checks:9,issues,pass:issues.length===0},null,2));
if(issues.length)process.exitCode=1;
