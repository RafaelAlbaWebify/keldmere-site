import { readFileSync } from "node:fs";
const read = (path) => readFileSync(path,"utf8");
const homepage=read("src/app/page.tsx");
const privacy=read("src/app/privacy/page.tsx");
const company=read("src/app/company/page.tsx");
const brand=read("BRAND.md");
const readme=read("README.md");
const docs=read("commercial/SALES-OPERATIONS-CHECKLIST.md");
const images=JSON.parse(read("commercial/IMAGE-ASSET-REGISTER.json")).assets;
const issues=[];
const check=(name,ok)=>{if(!ok)issues.push(name)};
check("Web-first offer missing on homepage",homepage.includes("Starter website project"));
check("Web-first offer missing in README",readme.includes("website design/development"));
check("Sales workflow missing website qualification",docs.includes("Website design/redesign:"));
check("Brand guidelines still focused on M365",brand.includes("Website Project") && brand.includes("Microsoft 365"));
check("Privacy inaccurately says fonts are requested",!privacy.includes("site loads fonts from Google Fonts"));
check("Homepage still directs premium Atrium gallery to legacy trades demo",!homepage.includes('href="/demos/trades/"'));
check("Homepage missing premium imagery",["hartwell-premium.webp","brightsmile-premium.webp","atrium-premium.webp"].every(f=>homepage.includes(f)&&images.some(a=>a.path==="public/images/"+f)));
check("Homepage missing contact or price paths",homepage.includes('id="contact"')&&homepage.includes('id="website-plans"')&&homepage.includes('id="services"'));
check("Static hosting disabled",read("next.config.ts").includes('output: "export"'));
check("Service information must precede detailed examples and prices",homepage.indexOf('id="services"') < homepage.indexOf('id="examples"') && homepage.indexOf('id="examples"') < homepage.indexOf('id="website-plans"'));
check("Registered legal identity inconsistent across pages",company.includes("WEBIFY LIMITED")&&company.includes("761605")&&homepage.includes("WEBIFY LIMITED")&&homepage.includes("761605")&&privacy.includes("WEBIFY LIMITED")&&privacy.includes("761605"));
check("Legal company page missing registered office",company.includes("N37 F1W4")&&company.includes("2 Bridge Street"));
check("Design studies incorrectly presented as customer proof",homepage.includes("fictional design studies")&&homepage.includes("not client commissions"));
check("Pricing disclaimer absent",homepage.includes("Indicative starting prices")&&homepage.includes("written scope"));
check("Privacy missing processing and rights context",privacy.includes("Data Protection Commission")&&privacy.includes("Namecheap")&&privacy.includes("Gmail"));
check("Prelaunch privacy control plan missing",read("commercial/PRIVACY-OPERATIONAL-ACCEPTANCE.md").includes("12 months")&&privacy.includes("12 months"));
check("Commercial decision document missing",read("commercial/PRELAUNCH-COMMERCIAL-DECISION.md").includes("conditional approval")&&read("src/app/working-with-us/page.tsx").includes("Website projects"));
console.log(JSON.stringify({checks:17,issues,pass:issues.length===0},null,2));
if(issues.length)process.exitCode=1;
